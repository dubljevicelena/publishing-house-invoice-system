    private void popuniKnjige() {
        for (Knjiga k : knjige) {
            cmbKnjiga.addItem(k);
        }
        if(cmbKnjiga.getItemCount() > 0){
            cmbKnjiga.setSelectedIndex(0);
        }
    }
    
