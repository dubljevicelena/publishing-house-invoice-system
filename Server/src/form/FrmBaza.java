    private void btnSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajActionPerformed
        String url = txtUrl.getText().trim();
        String username = txtUsername.getText().trim();
        String password = String.valueOf(txtPassword.getText()).trim();
        try{
            configuration.Configuration.getInstance().setProperty("url", url);
            configuration.Configuration.getInstance().setProperty("username", username);
            configuration.Configuration.getInstance().setProperty("password", password);

            configuration.Configuration.getInstance().sacuvajIzmene();
            JOptionPane.showMessageDialog(this, "Izmene su sacuvane!", "USPEH", JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
        }
        catch(HeadlessException | IOException ex){
            JOptionPane.showMessageDialog(this, "GRESKA, izmene nisu sacuvane!", "GRESKA", JOptionPane.ERROR_MESSAGE);
            
        }
    }//GEN-LAST:event_btnSacuvajActionPerformed

