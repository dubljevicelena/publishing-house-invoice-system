    private void btnSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajActionPerformed
        int port;
        try {
            port = Integer.parseInt(txtPort.getText());
        } catch (NumberFormatException numberFormatException) {
            JOptionPane.showMessageDialog(this, "Port mora biti broj!", "GRESKA", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if(port >= 0 && port <= 65535)
        {
            try {
                configuration.Configuration.getInstance().setProperty("port", String.valueOf(port));
                configuration.Configuration.getInstance().sacuvajIzmene();
                JOptionPane.showMessageDialog(this, "Sacuvano!", "USPEH", JOptionPane.INFORMATION_MESSAGE);
                this.dispose();
            } catch (IOException ex) {
                System.getLogger(FrmPort.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }
        }
        else
        {
            JOptionPane.showMessageDialog(this, "Port nije u dobrom opsegu!", "GRESKA", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSacuvajActionPerformed

